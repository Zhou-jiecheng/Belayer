#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SWE_RL_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
REPO_ROOT="$(cd "${SWE_RL_DIR}/.." && pwd)"
SLIME_DIR="${REPO_ROOT}/slime"

DEFAULT_PYTHON_BIN="/mnt/shared-storage-user/ailab-sys/zhoujiecheng/miniconda/envs/osworld/bin/python"
PYTHON_BIN="${PYTHON_BIN:-${DEFAULT_PYTHON_BIN}}"
TRAJ_ROOT="${TRAJ_ROOT:-${1:-${REPO_ROOT}/export/E2E/swe_rl_online_scheduler_adaptive_fast_restart_no_ckpt/swe_rollouts}}"
if [[ -z "${TRAJ_ROOT}" ]]; then
    echo "Usage: $0 <trajectory_root> [extra replay args...]" >&2
    exit 2
fi
if [[ $# -gt 0 ]]; then
    shift
fi

export SWE_ENV_SERVER_BIND_HOST="${SWE_ENV_SERVER_BIND_HOST:-127.0.0.1}"
export SWE_ENV_SERVER_PORT="${SWE_ENV_SERVER_PORT:-18090}"
export SWE_ENV_SERVER_HOST="${SWE_ENV_SERVER_HOST:-127.0.0.1}"
export SWE_ENV_SERVER_URL="${SWE_ENV_SERVER_URL:-http://${SWE_ENV_SERVER_HOST}:${SWE_ENV_SERVER_PORT}}"
export SWE_EXEC_SERVER_URLS="${SWE_EXEC_SERVER_URLS:-http://100.103.28.35:5000}"

export SWE_ENABLE_ONLINE_ENV_DOCKER_SCHEDULER="${SWE_ENABLE_ONLINE_ENV_DOCKER_SCHEDULER:-1}"
export SWE_CHECKPOINT_POLICY="never"
export SWE_FAULT_INJECTION_ENABLE="0"
export SWE_REPLAY_SEED="${SWE_REPLAY_SEED:-0}"
export SWE_SCHED_RANDOM_SEED="${SWE_SCHED_RANDOM_SEED:-${SWE_REPLAY_SEED}}"
export PYTHONHASHSEED="${PYTHONHASHSEED:-${SWE_REPLAY_SEED}}"

export ROLLOUT_BATCH_SIZE="${ROLLOUT_BATCH_SIZE:-16}"
export N_SAMPLES_PER_PROMPT="${N_SAMPLES_PER_PROMPT:-8}"
export TARGET_TOTAL_SAMPLES="${TARGET_TOTAL_SAMPLES:-$((ROLLOUT_BATCH_SIZE * N_SAMPLES_PER_PROMPT))}"
export SWE_SGLANG_SERVER_CONCURRENCY="${SWE_SGLANG_SERVER_CONCURRENCY:-1048576}"
export SWE_SCHED_INTERNAL_MAX_INFLIGHT="${SWE_SCHED_INTERNAL_MAX_INFLIGHT:-${SWE_SGLANG_SERVER_CONCURRENCY}}"

export SWE_SCHED_MAX_UNKNOWN_REPO_CONCURRENCY="${SWE_SCHED_MAX_UNKNOWN_REPO_CONCURRENCY:-48}"
export SWE_SCHED_MAX_ACTIVE_PROMPTS="${SWE_SCHED_MAX_ACTIVE_PROMPTS:-0}"
export SWE_SCHED_STARTUP_MAX_ACTIVE_PROMPTS="${SWE_SCHED_STARTUP_MAX_ACTIVE_PROMPTS:-${TARGET_TOTAL_SAMPLES}}"
export SWE_SCHED_STARTUP_CAP_DURATION_SEC="${SWE_SCHED_STARTUP_CAP_DURATION_SEC:-1}"

export SWE_SCHED_DISABLE_LIVE_STATS_POLLING="${SWE_SCHED_DISABLE_LIVE_STATS_POLLING:-0}"
export SWE_SCHED_ENABLE_LIVE_PROFILE_UPDATES="${SWE_SCHED_ENABLE_LIVE_PROFILE_UPDATES:-1}"
export SWE_SCHED_MIN_LIVE_PROFILE_SAMPLES="${SWE_SCHED_MIN_LIVE_PROFILE_SAMPLES:-2}"
export SWE_SCHED_MIN_PROFILE_MEMORY_BYTES="${SWE_SCHED_MIN_PROFILE_MEMORY_BYTES:-134217728}"
export SWE_SCHED_MAX_STATS_REQUESTS_PER_ROUND="${SWE_SCHED_MAX_STATS_REQUESTS_PER_ROUND:-4}"
export SWE_SCHED_STATS_REQUEST_SPACING_SEC="${SWE_SCHED_STATS_REQUEST_SPACING_SEC:-1}"
export SWE_SCHED_USE_RESOURCE_STATS_DIR="${SWE_SCHED_USE_RESOURCE_STATS_DIR:-0}"
export SWE_SCHED_VERBOSE_LOGGING="${SWE_SCHED_VERBOSE_LOGGING:-1}"

export SWE_SCHED_USE_REALTIME_SERVER_MEMORY="${SWE_SCHED_USE_REALTIME_SERVER_MEMORY:-1}"
export SWE_SCHED_USE_REALTIME_SERVER_CPU="${SWE_SCHED_USE_REALTIME_SERVER_CPU:-1}"
export SWE_SCHED_USE_REALTIME_SERVER_DISK="${SWE_SCHED_USE_REALTIME_SERVER_DISK:-1}"
export SWE_SCHED_SERVER_MEMORY_REFRESH_SEC="${SWE_SCHED_SERVER_MEMORY_REFRESH_SEC:-40}"
export SWE_SCHED_BLOCKED_LOG_INTERVAL_SEC="${SWE_SCHED_BLOCKED_LOG_INTERVAL_SEC:-5}"
export SWE_SCHED_VERBOSE_LOG_INTERVAL_SEC="${SWE_SCHED_VERBOSE_LOG_INTERVAL_SEC:-10}"
export SWE_SCHED_HEAD_BLOCK_REQUEUE_THRESHOLD="${SWE_SCHED_HEAD_BLOCK_REQUEUE_THRESHOLD:-100}"
export SWE_SCHED_HEAD_BLOCK_REQUEUE_OFFSET="${SWE_SCHED_HEAD_BLOCK_REQUEUE_OFFSET:-1}"
export SWE_SCHED_REALTIME_LOCAL_ACTIVE_DISCOUNT="${SWE_SCHED_REALTIME_LOCAL_ACTIVE_DISCOUNT:-1.0}"
export SWE_SCHED_DURATION_PRIORITY_REF_SEC="${SWE_SCHED_DURATION_PRIORITY_REF_SEC:-300}"
export SWE_SCHED_PRESERVE_PROMPT_ORDER="${SWE_SCHED_PRESERVE_PROMPT_ORDER:-False}"

export SWE_SCHED_MEMORY_OVERSELL_RATIO="${SWE_SCHED_MEMORY_OVERSELL_RATIO:-1.6}"
export SWE_SCHED_CPU_OVERSELL_RATIO="${SWE_SCHED_CPU_OVERSELL_RATIO:-32}" #num of cpu cores * 2
export SWE_SCHED_SAFETY_MARGIN="${SWE_SCHED_SAFETY_MARGIN:-0.9}"
export SWE_SCHED_MEMORY_PEAK_SCALE="${SWE_SCHED_MEMORY_PEAK_SCALE:-1}"
export SWE_SCHED_DISK_READ_OVERSELL_RATIO="${SWE_SCHED_DISK_READ_OVERSELL_RATIO:-1000.0}"
export SWE_SCHED_DISK_WRITE_OVERSELL_RATIO="${SWE_SCHED_DISK_WRITE_OVERSELL_RATIO:-1000.0}"

export SWE_RESOURCE_STATS_DIR="${SWE_RESOURCE_STATS_DIR:-""}"
export SWE_REPO_RESOURCE_STATS_PATH="${SWE_REPO_RESOURCE_STATS_PATH:-""}"
export SWE_POOL_MAX_TOTAL_LEASES="${SWE_POOL_MAX_TOTAL_LEASES:-1024}"
export SWE_MAX_CONTAINERS_PER_NODE="${SWE_MAX_CONTAINERS_PER_NODE:-1024}"
export SWE_POOL_MAX_CONCURRENT_ALLOCATES="${SWE_POOL_MAX_CONCURRENT_ALLOCATES:-64}"
export SWE_POOL_ALLOCATE_MIN_INTERVAL_SEC="${SWE_POOL_ALLOCATE_MIN_INTERVAL_SEC:-0.05}"
export SWE_POOL_CREATE_TIMEOUT_SEC="${SWE_POOL_CREATE_TIMEOUT_SEC:-180}"
export SWE_SCHED_DOCKER_CREATE_MAX_CONCURRENT="${SWE_SCHED_DOCKER_CREATE_MAX_CONCURRENT:-64}"
export SWE_SCHED_DOCKER_CREATE_MIN_INTERVAL_SEC="${SWE_SCHED_DOCKER_CREATE_MIN_INTERVAL_SEC:-0.05}"
export SWE_MAX_CONCURRENT_DOCKER_CREATE="${SWE_MAX_CONCURRENT_DOCKER_CREATE:-${SWE_SCHED_DOCKER_CREATE_MAX_CONCURRENT}}"
export SWE_DOCKER_CREATE_MIN_INTERVAL_SEC="${SWE_DOCKER_CREATE_MIN_INTERVAL_SEC:-${SWE_SCHED_DOCKER_CREATE_MIN_INTERVAL_SEC}}"

export SWE_EXEC_STATS_SAMPLER_ENABLE="${SWE_EXEC_STATS_SAMPLER_ENABLE:-1}"
export SWE_EXEC_STATS_BACKEND="${SWE_EXEC_STATS_BACKEND:-cgroup}"
export SWE_EXEC_STATS_SAMPLER_INTERVAL_SEC="${SWE_EXEC_STATS_SAMPLER_INTERVAL_SEC:-4}"
export SWE_EXEC_STATS_CACHE_TTL_SEC="${SWE_EXEC_STATS_CACHE_TTL_SEC:-5}"
export SWE_EXEC_STATS_BATCH_MAX_CONTAINERS="${SWE_EXEC_STATS_BATCH_MAX_CONTAINERS:-32}"
export SWE_EXEC_STATS_CPU_SAMPLE_MIN_ELAPSED_SEC="${SWE_EXEC_STATS_CPU_SAMPLE_MIN_ELAPSED_SEC:-5}"
export SWE_EXEC_STATS_MAX_CONTAINER_CPU_PERCENT="${SWE_EXEC_STATS_MAX_CONTAINER_CPU_PERCENT:-1000}"
export SWE_EXEC_ACTION_STATS_SAMPLER_ENABLE="${SWE_EXEC_ACTION_STATS_SAMPLER_ENABLE:-1}"
export SWE_EXEC_ACTION_STATS_INTERVAL_SEC="${SWE_EXEC_ACTION_STATS_INTERVAL_SEC:-1}"
export SWE_EXEC_ACTION_STATS_COMMAND_TIMEOUT_SEC="${SWE_EXEC_ACTION_STATS_COMMAND_TIMEOUT_SEC:-5}"
export SWE_EXEC_ACTION_STATS_BATCH_MAX_CONTAINERS="${SWE_EXEC_ACTION_STATS_BATCH_MAX_CONTAINERS:-32}"
export SWE_SCHED_MAX_STATS_REQUESTS_PER_ROUND="${SWE_SCHED_MAX_STATS_REQUESTS_PER_ROUND:-32}"
export SWE_SCHED_STATS_REQUEST_SPACING_SEC="${SWE_SCHED_STATS_REQUEST_SPACING_SEC:-0}"
export SWE_SCHED_SAMPLING_INTERVAL_SEC="${SWE_SCHED_SAMPLING_INTERVAL_SEC:-10}"
export SWE_SCHED_MAX_REQUESTS_PER_RESOURCE_UPDATE="${SWE_SCHED_MAX_REQUESTS_PER_RESOURCE_UPDATE:-4}"

EXPERIMENT_OUTPUT_ROOT="${EXPERIMENT_OUTPUT_ROOT:-${REPO_ROOT}/export/swe_online_scheduler_replay_$(date +%Y%m%d_%H%M%S)}"
mkdir -p "${EXPERIMENT_OUTPUT_ROOT}"
POOL_LOG="${POOL_LOG:-${EXPERIMENT_OUTPUT_ROOT}/swe_env_pool_server.log}"
EXPERIMENT_LOG="${EXPERIMENT_LOG:-${EXPERIMENT_OUTPUT_ROOT}/experiment.log}"

ALL_EXEC_HOSTS="$(echo "${SWE_EXEC_SERVER_URLS}" | tr ',' '\n' | sed -E 's#https?://([^:/]+).*#\1#' | tr '\n' ',' | sed 's/,$//')"
export NO_PROXY="localhost,127.0.0.1,${SWE_ENV_SERVER_HOST},${ALL_EXEC_HOSTS}"
export no_proxy="${NO_PROXY}"

SWE_POOL_PID=""
cleanup() {
    set +e
    if [[ -n "${SWE_POOL_PID}" ]] && kill -0 "${SWE_POOL_PID}" 2>/dev/null; then
        kill "${SWE_POOL_PID}" || true
    fi
}
trap cleanup EXIT INT TERM

echo "[scheduler-replay] output_root=${EXPERIMENT_OUTPUT_ROOT}"
echo "[scheduler-replay] trajectory_root=${TRAJ_ROOT}"
echo "[scheduler-replay] env_pool_url=${SWE_ENV_SERVER_URL}"
echo "[scheduler-replay] exec_server_urls=${SWE_EXEC_SERVER_URLS}"
echo "[scheduler-replay] batch_shape=${ROLLOUT_BATCH_SIZE}x${N_SAMPLES_PER_PROMPT} target_total=${TARGET_TOTAL_SAMPLES}"
echo "[scheduler-replay] seed=${SWE_REPLAY_SEED} pythonhashseed=${PYTHONHASHSEED}"
if [[ -n "${EXPERIMENT_LIMIT:-}" ]]; then
    echo "[scheduler-replay] debug_limit=${EXPERIMENT_LIMIT} (applied after batch-shape selection)"
fi
echo "[scheduler-replay] memory_oversell=${SWE_SCHED_MEMORY_OVERSELL_RATIO}"
echo "[scheduler-replay] cpu_oversell=${SWE_SCHED_CPU_OVERSELL_RATIO}"

PYTHONPATH="${SLIME_DIR}:${SWE_RL_DIR}:${SWE_RL_DIR}/server:${PYTHONPATH:-}" \
"${PYTHON_BIN}" -m swe_env_pool_server \
    --host "${SWE_ENV_SERVER_BIND_HOST}" \
    --port "${SWE_ENV_SERVER_PORT}" \
    --exec-server-urls "${SWE_EXEC_SERVER_URLS}" \
    --max-containers-per-node "${SWE_MAX_CONTAINERS_PER_NODE}" \
    --max-total-leases "${SWE_POOL_MAX_TOTAL_LEASES}" \
    --max-concurrent-allocates "${SWE_POOL_MAX_CONCURRENT_ALLOCATES}" \
    --allocate-min-interval-sec "${SWE_POOL_ALLOCATE_MIN_INTERVAL_SEC}" \
    --create-timeout-sec "${SWE_POOL_CREATE_TIMEOUT_SEC}" \
    > "${POOL_LOG}" 2>&1 &
SWE_POOL_PID=$!

for _ in {1..60}; do
    if curl -fsS "${SWE_ENV_SERVER_URL}/healthz" >/dev/null 2>&1; then
        break
    fi
    sleep 1
done

if ! curl -fsS "${SWE_ENV_SERVER_URL}/healthz" >/dev/null 2>&1; then
    echo "ERROR: swe_env_pool_server failed to start. See ${POOL_LOG}" >&2
    exit 1
fi
# REORDER_MODE="original"
ARGS=(
    "${TRAJ_ROOT}"
    "--base-url" "${SWE_ENV_SERVER_URL}"
    "--output-root" "${EXPERIMENT_OUTPUT_ROOT}"
    "--max-inflight" "${SWE_SCHED_INTERNAL_MAX_INFLIGHT}"
    "--rollout-batch-size" "${ROLLOUT_BATCH_SIZE}"
    "--n-samples-per-prompt" "${N_SAMPLES_PER_PROMPT}"
    "--seed" "${SWE_REPLAY_SEED}"
    "--reorder-mode" "${REORDER_MODE:-breadth-first}"
    "--llm-delay-scale" "${SWE_REPLAY_LLM_DELAY_SCALE:-1.0}"
    "--scheduler-resource-refresh-sec" "${SWE_REPLAY_SCHED_RESOURCE_REFRESH_SEC:-40.0}"
    "--scheduler-resource-warmup-timeout-sec" "${SWE_REPLAY_SCHED_RESOURCE_WARMUP_TIMEOUT_SEC:-60}"
)

if [[ -n "${EXPERIMENT_LIMIT:-}" ]]; then
    ARGS+=("--limit" "${EXPERIMENT_LIMIT}")
fi

if [[ "${SWE_REPLAY_DISABLE_BATCH_SHAPE_FILTER:-0}" == "1" ]]; then
    ARGS+=("--disable-batch-shape-filter")
fi

if [[ "${SWE_REPLAY_SKIP_EVAL:-0}" == "1" ]]; then
    ARGS+=("--skip-eval")
fi

if [[ "${SWE_REPLAY_ALLOW_ZERO_SCHEDULER_BUDGET:-0}" == "1" ]]; then
    ARGS+=("--allow-zero-scheduler-budget")
fi

if [[ $# -gt 0 ]]; then
    ARGS+=("$@")
fi

PYTHONPATH="${SLIME_DIR}:${SWE_RL_DIR}:${SWE_RL_DIR}/server:${PYTHONPATH:-}" \
"${PYTHON_BIN}" "${SWE_RL_DIR}/tools/replay_swe_online_scheduler_experiment.py" \
    "${ARGS[@]}" \
    2>&1 | tee "${EXPERIMENT_LOG}"

echo "[scheduler-replay] done"
echo "[scheduler-replay] pool_log=${POOL_LOG}"
echo "[scheduler-replay] experiment_log=${EXPERIMENT_LOG}"
echo "[scheduler-replay] output_root=${EXPERIMENT_OUTPUT_ROOT}"
