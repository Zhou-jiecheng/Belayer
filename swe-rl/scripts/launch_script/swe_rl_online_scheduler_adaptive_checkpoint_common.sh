    echo "${prefix} SWE_MAX_CONCURRENT_DOCKER_CREATE=${SWE_MAX_CONCURRENT_DOCKER_CREATE}"
    echo "${prefix} SWE_MAX_CONCURRENT_EVAL=${SWE_MAX_CONCURRENT_EVAL}"
    echo "${prefix} SWE_MAX_CONCURRENT_DIFF=${SWE_MAX_CONCURRENT_DIFF}"
    echo "${prefix} SWE_POOL_CREATE_TIMEOUT_SEC=${SWE_POOL_CREATE_TIMEOUT_SEC}"
    echo "${prefix} SWE_ROLLOUT_TIMEOUT=${SWE_ROLLOUT_TIMEOUT}"
}
